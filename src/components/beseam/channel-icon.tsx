export function channelBrand(channel?: string | null): ChannelBrand {
  if (!channel) return "generic";
  const key = channel
    .trim()
    .toLowerCase()
    .replace(/[\s.-]+/g, "_");
  return CHANNEL_BRANDS[key] ?? "generic";
}

const FALLBACK_ICONS = {
  microsoft: Bot,
  agentic: FileCode2,
  store: Store,
  generic: Globe,
} as const;

/**
 * Brand mark for one answer surface. Decorative unless `title` is given.
 */
export function ChannelIcon({
  channel,
  brand,
  className,
  title,
}: {
  channel?: string | null;
  brand?: ChannelBrand;
  className?: string;
  title?: string;
}) {
  const resolved = brand ?? channelBrand(channel);

  if (resolved in BRAND_PATHS) {
    return (
      <svg
        viewBox="0 0 24 24"
        fill="currentColor"
        role={title ? "img" : "presentation"}
        aria-hidden={title ? undefined : true}
        className={cn("h-4 w-4 shrink-0", className)}
      >
        {title ? <title>{title}</title> : null}
        <path d={BRAND_PATHS[resolved as BrandMark]} />
      </svg>
    );
  }

  const Fallback = FALLBACK_ICONS[resolved as keyof typeof FALLBACK_ICONS];
  return (
    <Fallback
      aria-hidden={title ? undefined : true}
      aria-label={title}
      className={cn("h-4 w-4 shrink-0", className)}
    />
  );
}

